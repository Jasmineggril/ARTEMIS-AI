/**
 * ARTEMIS AI — public read-only API (Consulta Pública).
 *
 * Only occurrences from import batches explicitly published by an
 * organization administrator (import_batches.visibility = 'publico') are
 * exposed. Coordinates are rounded to 2 decimals (~1 km) and free-text /
 * raw fields (notes, raw_data, source_reference, cause) are never returned.
 * These are historical imported records — not satellite hotspots and not
 * real-time monitoring.
 */
import type { Express, Response } from "express";
import { z } from "zod";
import { and, eq, gte, lte, sql, desc, isNull, type SQL } from "drizzle-orm";
import { db } from "./db";
import { fireOccurrences, importBatches, organizations, satelliteHotspots, sourceSyncRuns, dataSources, sisfogoRoiRecords } from "@shared/schema";
import { rateLimit } from "./security";
import { hasPostgisGeom } from "./spatial";
import { BR_STATES } from "@shared/br-states";

const date = z.string().regex(/^\d{4}-\d{2}-\d{2}$/);
export const publicFilterSchema = z.object({
  state: z.string().trim().toUpperCase().refine((s) => (BR_STATES as readonly string[]).includes(s), "UF inválida.").optional(),
  municipality: z.string().trim().min(2).max(120).optional(),
  from: date.optional(),
  to: date.optional(),
  hourFrom: z.coerce.number().int().min(0).max(23).optional(),
  hourTo: z.coerce.number().int().min(0).max(23).optional(),
  compareFrom: date.optional(),
  compareTo: date.optional(),
});
type Filter = z.infer<typeof publicFilterSchema>;

/** Local hour (0–23), generated by PostgreSQL from the original time text (migration 0005). */
const hourExpr = fireOccurrences.occurredHour;

function conditions(f: Filter, range?: { from?: string; to?: string }): SQL[] {
  const c: SQL[] = [eq(importBatches.visibility, "publico")];
  if (f.state) c.push(eq(fireOccurrences.state, f.state));
  if (f.municipality) c.push(sql`lower(${fireOccurrences.municipality}) = lower(${f.municipality})`);
  const from = range ? range.from : f.from;
  const to = range ? range.to : f.to;
  if (from) c.push(gte(fireOccurrences.occurredOn, from));
  if (to) c.push(lte(fireOccurrences.occurredOn, to));
  if (f.hourFrom !== undefined) c.push(sql`${hourExpr} >= ${f.hourFrom}`);
  if (f.hourTo !== undefined) c.push(sql`${hourExpr} <= ${f.hourTo}`);
  return c;
}

function handle(fn: (req: any, res: Response) => Promise<unknown>) {
  return async (req: any, res: Response, next: (e?: unknown) => void) => {
    try {
      await fn(req, res);
    } catch (err) {
      if (err instanceof z.ZodError) return res.status(400).json({ message: err.errors[0].message });
      next(err);
    }
  };
}

const round2 = (v: number | null) => (v == null ? null : Math.round(v * 100) / 100);

async function countWhere(c: SQL[]) {
  const [{ n }] = await db
    .select({ n: sql<number>`count(*)::int` })
    .from(fireOccurrences)
    .innerJoin(importBatches, eq(importBatches.id, fireOccurrences.importBatchId))
    .where(and(...c));
  return n;
}

// ── Satellite hotspots (INPE) — public data, separate from imported records ───
export const sisfogoFilterSchema = z.object({
  state: z.string().trim().toUpperCase().refine((s) => (BR_STATES as readonly string[]).includes(s), "UF inválida.").optional(),
  municipality: z.string().trim().min(2).max(120).optional(),
  from: date.optional(),
  to: date.optional(),
}).refine((f) => !f.from || !f.to || f.from <= f.to, "Data inicial posterior à final.");

const bboxParam = z.string().max(120).transform((v, ctx) => {
  const n = v.split(",").map(Number);
  const [minLng, minLat, maxLng, maxLat] = n;
  if (n.length !== 4 || !n.every(Number.isFinite) || minLng >= maxLng || minLat >= maxLat || minLat < -90 || maxLat > 90 || minLng < -180 || maxLng > 180) {
    ctx.addIssue({ code: "custom", message: "bbox inválido (minLng,minLat,maxLng,maxLat)." });
    return z.NEVER;
  }
  return n as [number, number, number, number];
});
export const sisfogoPointsSchema = z.object({
  state: z.string().trim().toUpperCase().refine((s) => (BR_STATES as readonly string[]).includes(s), "UF inválida.").optional(),
  municipality: z.string().trim().min(2).max(120).optional(),
  from: date.optional(),
  to: date.optional(),
  localityType: z.string().trim().min(2).max(120).optional(),
  bbox: bboxParam.optional(),
  limit: z.coerce.number().int().min(1).max(5000).default(2000),
  offset: z.coerce.number().int().min(0).max(1_000_000).default(0),
}).refine((f) => !f.from || !f.to || f.from <= f.to, "Data inicial posterior à final.");

export const hotspotFilterSchema = z.object({
  state: z.string().trim().toUpperCase().refine((s) => (BR_STATES as readonly string[]).includes(s), "UF inválida.").optional(),
  municipality: z.string().trim().min(2).max(120).optional(),
  satellite: z.string().trim().max(40).optional(),
  from: date.optional(),
  to: date.optional(),
}).transform((f, ctx) => {
  const to = f.to ?? new Date().toISOString().slice(0, 10);
  const from = f.from ?? new Date(Date.parse(`${to}T00:00:00Z`) - 86_400_000).toISOString().slice(0, 10);
  const span = (Date.parse(`${to}T00:00:00Z`) - Date.parse(`${from}T00:00:00Z`)) / 86_400_000;
  if (span < 0) ctx.addIssue({ code: "custom", message: "Data inicial posterior à final." });
  if (span > 31) ctx.addIssue({ code: "custom", message: "Intervalo máximo de 31 dias para focos de calor." });
  return { ...f, from, to };
});

function hotspotConditions(f: z.infer<typeof hotspotFilterSchema>): SQL[] {
  const c: SQL[] = [
    gte(satelliteHotspots.detectedAt, new Date(`${f.from}T00:00:00Z`)),
    lte(satelliteHotspots.detectedAt, new Date(`${f.to}T23:59:59.999Z`)),
  ];
  if (f.state) c.push(eq(satelliteHotspots.state, f.state));
  if (f.municipality) c.push(sql`lower(${satelliteHotspots.municipality}) = lower(${f.municipality})`);
  if (f.satellite) c.push(eq(satelliteHotspots.satellite, f.satellite));
  return c;
}

export const HOTSPOT_NOTICE =
  "Focos de calor detectados por satélite (INPE — Programa Queimadas). Foco de calor não é incêndio confirmado; " +
  "o mesmo fogo pode ser detectado por vários satélites, então contagens de satélites diferentes não devem ser somadas para comparar períodos.";

export function registerPublicRoutes(app: Express) {
  const limiter = rateLimit({ windowMs: 60_000, max: 60, key: "public" });

  app.get("/api/public/hotspots", limiter, handle(async (req, res) => {
    const f = hotspotFilterSchema.parse(req.query);
    const LIMIT = 5000;
    const rows = await db
      .select({
        detectedAt: satelliteHotspots.detectedAt, satellite: satelliteHotspots.satellite,
        latitude: satelliteHotspots.latitude, longitude: satelliteHotspots.longitude,
        municipality: satelliteHotspots.municipality, state: satelliteHotspots.state, biome: satelliteHotspots.biome,
        frpMw: satelliteHotspots.frpMw, daysWithoutRain: satelliteHotspots.daysWithoutRain,
      })
      .from(satelliteHotspots)
      .where(and(...hotspotConditions(f)))
      .orderBy(desc(satelliteHotspots.detectedAt))
      .limit(LIMIT + 1);
    res.setHeader("Cache-Control", "public, max-age=300");
    res.json({ truncated: rows.length > LIMIT, points: rows.slice(0, LIMIT), period: { from: f.from, to: f.to }, notice: HOTSPOT_NOTICE });
  }));

  // Aggregated grid for overview maps (~25 km cells by default). Small, cacheable payload.
  app.get("/api/public/hotspots/grid", limiter, handle(async (req, res) => {
    const f = hotspotFilterSchema.parse(req.query);
    const { cell } = z.object({ cell: z.coerce.number().min(0.05).max(2).default(0.25) }).parse({ cell: req.query.cell });
    const c = and(...hotspotConditions(f));
    const cells = await db
      .select({
        lat: sql<number>`(floor(${satelliteHotspots.latitude} / ${cell}::float8) * ${cell}::float8 + ${cell}::float8 / 2)::float8`,
        lng: sql<number>`(floor(${satelliteHotspots.longitude} / ${cell}::float8) * ${cell}::float8 + ${cell}::float8 / 2)::float8`,
        n: sql<number>`count(*)::int`,
      })
      .from(satelliteHotspots).where(c).groupBy(sql`1`, sql`2`);
    const states = await db
      .select({
        state: satelliteHotspots.state, n: sql<number>`count(*)::int`,
        lat: sql<number>`avg(${satelliteHotspots.latitude})::float8`, lng: sql<number>`avg(${satelliteHotspots.longitude})::float8`,
      })
      .from(satelliteHotspots).where(and(c, sql`${satelliteHotspots.state} is not null`))
      .groupBy(satelliteHotspots.state).orderBy(desc(sql`2`));
    const [{ municipalities }] = await db
      .select({ municipalities: sql<number>`count(distinct ${satelliteHotspots.municipalityIbgeCode})::int` })
      .from(satelliteHotspots).where(c);
    const [last] = await db.select({ at: sql<string | null>`max(${sourceSyncRuns.finishedAt})` })
      .from(sourceSyncRuns).innerJoin(dataSources, eq(dataSources.id, sourceSyncRuns.sourceId))
      .where(and(eq(dataSources.key, "inpe-queimadas"), eq(sourceSyncRuns.status, "sucesso")));
    res.setHeader("Cache-Control", "public, max-age=300");
    res.json({
      period: { from: f.from, to: f.to }, cell, total: cells.reduce((a, x) => a + x.n, 0),
      municipalities, cells, states, lastSyncAt: last?.at ?? null, notice: HOTSPOT_NOTICE,
    });
  }));

  app.get("/api/public/hotspots/summary", limiter, handle(async (req, res) => {
    const f = hotspotFilterSchema.parse(req.query);
    const c = and(...hotspotConditions(f));
    const [{ total }] = await db.select({ total: sql<number>`count(*)::int` }).from(satelliteHotspots).where(c);
    const bySatellite = await db.select({ satellite: satelliteHotspots.satellite, n: sql<number>`count(*)::int` })
      .from(satelliteHotspots).where(c).groupBy(satelliteHotspots.satellite).orderBy(desc(sql`2`));
    const byDay = await db.select({ day: sql<string>`to_char(${satelliteHotspots.detectedAt} at time zone 'UTC', 'YYYY-MM-DD')`, n: sql<number>`count(*)::int` })
      .from(satelliteHotspots).where(c).groupBy(sql`1`).orderBy(sql`1`);
    const topMunicipalities = await db.select({ municipality: satelliteHotspots.municipality, state: satelliteHotspots.state, n: sql<number>`count(*)::int` })
      .from(satelliteHotspots).where(and(c, sql`${satelliteHotspots.municipality} is not null`))
      .groupBy(satelliteHotspots.municipality, satelliteHotspots.state).orderBy(desc(sql`3`)).limit(10);
    const [last] = await db.select({ at: sql<string | null>`max(${sourceSyncRuns.finishedAt})` })
      .from(sourceSyncRuns).innerJoin(dataSources, eq(dataSources.id, sourceSyncRuns.sourceId))
      .where(and(eq(dataSources.key, "inpe-queimadas"), eq(sourceSyncRuns.status, "sucesso")));
    res.setHeader("Cache-Control", "public, max-age=300");
    res.json({ period: { from: f.from, to: f.to }, total, bySatellite, byDay, topMunicipalities, lastSyncAt: last?.at ?? null, notice: HOTSPOT_NOTICE,
      source: { name: "INPE — Programa Queimadas", url: "https://terrabrasilis.dpi.inpe.br/queimadas/portal/" } });
  }));


  // ── Sisfogo (Ibama/Prevfogo) ROI records (migrations 0010/0011) ─────────
  // Only ROIs the source currently publishes; dates are Brasília-time dates of the
  // published UTC start instant. Free-text place names are never exposed here.
  app.get("/api/public/sisfogo/summary", limiter, handle(async (req, res) => {
    const f = sisfogoFilterSchema.parse(req.query);
    const t = sisfogoRoiRecords;
    const c = and(
      f.state ? eq(t.state, f.state) : undefined,
      f.municipality ? sql`lower(${t.municipality}) = lower(${f.municipality})` : undefined,
      f.from ? gte(t.startedOn, f.from) : undefined,
      f.to ? lte(t.startedOn, f.to) : undefined,
      isNull(t.unavailableSince),
    );
    const [agg] = await db.select({
      total: sql<number>`count(*)::int`,
      withArea: sql<number>`count(${t.burnedAreaHa})::int`,
      burnedAreaHa: sql<number | null>`round(sum(${t.burnedAreaHa})::numeric, 1)::float8`,
      firstDay: sql<string | null>`min(${t.startedOn})::text`,
      lastDay: sql<string | null>`max(${t.startedOn})::text`,
    }).from(t).where(c);
    const byState = await db.select({ state: t.state, n: sql<number>`count(*)::int` })
      .from(t).where(and(c, sql`${t.state} is not null`)).groupBy(t.state).orderBy(desc(sql`2`)).limit(27);
    const byMonth = await db.select({ month: sql<string>`to_char(${t.startedOn}, 'YYYY-MM')`, n: sql<number>`count(*)::int` })
      .from(t).where(and(c, sql`${t.startedOn} is not null`)).groupBy(sql`1`).orderBy(sql`1`);
    const recent = await db.select({
      roiNumber: t.roiNumber, startedOn: t.startedOn, startedAt: t.startedAt, extinguishedAt: t.extinguishedAt,
      municipality: t.municipality, state: t.state, biome: t.biome, localityType: t.localityType,
      burnedAreaHa: t.burnedAreaHa, vegetation: t.vegetation, rectified: t.rectified,
    }).from(t).where(c).orderBy(sql`${t.startedAt} desc nulls last`).limit(20);
    const [last] = await db.select({ at: sql<string | null>`to_char(max(${sourceSyncRuns.finishedAt}) AT TIME ZONE 'UTC', 'YYYY-MM-DD"T"HH24:MI:SS"Z"')` })
      .from(sourceSyncRuns).innerJoin(dataSources, eq(dataSources.id, sourceSyncRuns.sourceId))
      .where(and(eq(dataSources.key, "sisfogo-roi"), eq(sourceSyncRuns.status, "sucesso")));
    const [complete] = await db.select({ at: sql<string | null>`to_char(max(${sourceSyncRuns.finishedAt}) AT TIME ZONE 'UTC', 'YYYY-MM-DD"T"HH24:MI:SS"Z"')` })
      .from(sourceSyncRuns).innerJoin(dataSources, eq(dataSources.id, sourceSyncRuns.sourceId))
      .where(and(eq(dataSources.key, "sisfogo-roi"), eq(sourceSyncRuns.status, "sucesso"),
        sql`${sourceSyncRuns.params}->>'mode' = 'completa'`, sql`${sourceSyncRuns.progress}->>'stoppedBecause' = 'fim_da_lista'`));
    res.setHeader("Cache-Control", "public, max-age=300");
    res.json({
      ...agg, byState, byMonth, recent, lastSyncAt: last?.at ?? null, lastCompleteSyncAt: complete?.at ?? null,
      timeNote: "Datas no horário de Brasília, convertidas do instante UTC publicado pelo Sisfogo.",
      notice: "Registros de Ocorrência de Incêndio (ROI) finalizados e publicados pelo Ibama/Prevfogo no Sisfogo. Cobrem apenas os órgãos que aderiram ao Sisfogo — não representam todos os incêndios do país. Área queimada é estimativa informada no registro.",
      source: { name: "Ibama/Prevfogo — Sisfogo", url: "https://sisfogo.sistema.gov.br" },
    });
  }));

  // Map layer: official Sisfogo ROIs as points (bounded window, paginated). Same
  // filters as the summary plus locality type and a bounding box; free-text place
  // names are never returned.
  app.get("/api/public/sisfogo/points", limiter, handle(async (req, res) => {
    const f = sisfogoPointsSchema.parse(req.query);
    // Filter on fire_occurrences (lat/lng index, or GiST on geom with PostGIS); join the mirror for display fields.
    const conds: SQL[] = [
      sql`s.key = 'sisfogo-roi'`, sql`f.organization_id IS NULL`, sql`f.source_available`, sql`f.latitude IS NOT NULL`,
    ];
    if (f.state) conds.push(sql`f.state = ${f.state}`);
    if (f.municipality) conds.push(sql`lower(f.municipality) = lower(${f.municipality})`);
    if (f.from) conds.push(sql`f.occurred_on >= ${f.from}`);
    if (f.to) conds.push(sql`f.occurred_on <= ${f.to}`);
    if (f.localityType) conds.push(sql`m.locality_type = ${f.localityType}`);
    if (f.bbox) {
      const [minLng, minLat, maxLng, maxLat] = f.bbox;
      conds.push(await hasPostgisGeom()
        ? sql`f.geom && ST_MakeEnvelope(${minLng}, ${minLat}, ${maxLng}, ${maxLat}, 4326)::geography`
        : sql`f.latitude BETWEEN ${minLat} AND ${maxLat} AND f.longitude BETWEEN ${minLng} AND ${maxLng}`);
    }
    const where = sql.join(conds, sql` AND `);
    const from = sql`FROM fire_occurrences f JOIN data_sources s ON s.id = f.data_source_id
      JOIN sisfogo_roi_records m ON m.source_id = f.data_source_id AND m.external_id = f.external_id`;
    const totalRes = await db.execute<{ total: number }>(sql`SELECT count(*)::int AS total ${from} WHERE ${where}`);
    const total = Number(totalRes.rows[0]?.total ?? 0);
    const pts = await db.execute<Record<string, unknown>>(sql`
      SELECT f.id, f.source_reference AS "roiNumber",
             to_char(f.occurred_at AT TIME ZONE 'UTC', 'YYYY-MM-DD"T"HH24:MI:SS"Z"') AS "startedAt", f.occurred_on::text AS "startedOn",
             to_char(m.extinguished_at AT TIME ZONE 'UTC', 'YYYY-MM-DD"T"HH24:MI:SS"Z"') AS "extinguishedAt", f.latitude, f.longitude, f.municipality, f.state, m.biome,
             m.locality_type AS "localityType", f.affected_area AS "burnedAreaHa", m.rectified, m.revision
      ${from} WHERE ${where}
      ORDER BY f.occurred_at DESC NULLS LAST, f.id DESC LIMIT ${f.limit} OFFSET ${f.offset}`);
    const points = pts.rows;
    const t = sisfogoRoiRecords;
    const types = await db.selectDistinct({ v: t.localityType }).from(t).where(and(isNull(t.unavailableSince), sql`${t.localityType} IS NOT NULL`)).orderBy(t.localityType);
    const [complete] = await db.select({ at: sql<string | null>`to_char(max(${sourceSyncRuns.finishedAt}) AT TIME ZONE 'UTC', 'YYYY-MM-DD"T"HH24:MI:SS"Z"')` })
      .from(sourceSyncRuns).innerJoin(dataSources, eq(dataSources.id, sourceSyncRuns.sourceId))
      .where(and(eq(dataSources.key, "sisfogo-roi"), eq(sourceSyncRuns.status, "sucesso"),
        sql`${sourceSyncRuns.params}->>'mode' = 'completa'`, sql`${sourceSyncRuns.progress}->>'stoppedBecause' = 'fim_da_lista'`));
    res.setHeader("Cache-Control", "public, max-age=300");
    res.json({
      total, limit: f.limit, offset: f.offset, truncated: f.offset + points.length < total,
      points, localityTypes: types.map((x) => x.v), lastCompleteSyncAt: complete?.at ?? null,
      source: { name: "Ibama/Prevfogo — Sisfogo", url: "https://sisfogo.sistema.gov.br" },
    });
  }));

  app.get("/api/public/occurrences", limiter, handle(async (req, res) => {
    const f = publicFilterSchema.parse(req.query);
    const LIMIT = 3000;
    const rows = await db
      .select({
        date: fireOccurrences.occurrenceDate,
        time: fireOccurrences.occurrenceTime,
        municipality: fireOccurrences.municipality,
        state: fireOccurrences.state,
        latitude: fireOccurrences.latitude,
        longitude: fireOccurrences.longitude,
        type: fireOccurrences.occurrenceType,
        source: importBatches.sourceName,
      })
      .from(fireOccurrences)
      .innerJoin(importBatches, eq(importBatches.id, fireOccurrences.importBatchId))
      .where(and(...conditions(f)))
      .orderBy(sql`${fireOccurrences.occurredOn} desc nulls last`)
      .limit(LIMIT + 1);
    res.setHeader("Cache-Control", "public, max-age=300");
    res.json({
      truncated: rows.length > LIMIT,
      points: rows.slice(0, LIMIT).map((r) => ({ ...r, latitude: round2(r.latitude), longitude: round2(r.longitude) })),
      notice: "Registros históricos importados e publicados por organizações. Coordenadas aproximadas (~1 km). Não são focos de calor por satélite nem monitoramento em tempo real.",
    });
  }));

  app.get("/api/public/summary", limiter, handle(async (req, res) => {
    const f = publicFilterSchema.parse(req.query);
    const c = conditions(f);
    const total = await countWhere(c);
    const byMonth = await db
      .select({ month: sql<string>`to_char(${fireOccurrences.occurredOn}, 'YYYY-MM')`, n: sql<number>`count(*)::int` })
      .from(fireOccurrences).innerJoin(importBatches, eq(importBatches.id, fireOccurrences.importBatchId))
      .where(and(...c, sql`${fireOccurrences.occurredOn} is not null`)).groupBy(sql`1`).orderBy(sql`1`);
    const byHourRows = await db
      .select({ hour: hourExpr, n: sql<number>`count(*)::int` })
      .from(fireOccurrences).innerJoin(importBatches, eq(importBatches.id, fireOccurrences.importBatchId))
      .where(and(...c, sql`${hourExpr} is not null`)).groupBy(sql`1`).orderBy(sql`1`);
    const byHour = Array.from({ length: 24 }, (_, h) => ({ hour: h, n: byHourRows.find((r) => r.hour === h)?.n ?? 0 }));
    const topMunicipalities = await db
      .select({ municipality: fireOccurrences.municipality, state: fireOccurrences.state, n: sql<number>`count(*)::int` })
      .from(fireOccurrences).innerJoin(importBatches, eq(importBatches.id, fireOccurrences.importBatchId))
      .where(and(...c, sql`${fireOccurrences.municipality} is not null`))
      .groupBy(fireOccurrences.municipality, fireOccurrences.state).orderBy(desc(sql`3`)).limit(10);
    const sources = await db
      .select({
        source: importBatches.sourceName, organization: organizations.name,
        batches: sql<number>`count(distinct ${importBatches.id})::int`, publishedAt: sql<string>`max(${importBatches.publishedAt})`,
      })
      .from(importBatches).innerJoin(organizations, eq(organizations.id, importBatches.organizationId))
      .where(eq(importBatches.visibility, "publico"))
      .groupBy(importBatches.sourceName, organizations.name);

    let comparison = null;
    if (f.compareFrom && f.compareTo) {
      const a = await countWhere(conditions(f, { from: f.from, to: f.to }));
      const b = await countWhere(conditions(f, { from: f.compareFrom, to: f.compareTo }));
      comparison = {
        current: { from: f.from ?? null, to: f.to ?? null, total: a },
        previous: { from: f.compareFrom, to: f.compareTo, total: b },
        changePct: b > 0 ? Math.round(((a - b) / b) * 100) : null,
      };
    }
    res.setHeader("Cache-Control", "public, max-age=300");
    res.json({ generatedAt: new Date().toISOString(), total, byMonth, byHour, topMunicipalities, sources, comparison });
  }));

  app.get("/api/public/municipalities", limiter, handle(async (req, res) => {
    const { state } = z.object({ state: publicFilterSchema.shape.state }).parse(req.query);
    const rows = await db
      .selectDistinct({ municipality: fireOccurrences.municipality })
      .from(fireOccurrences).innerJoin(importBatches, eq(importBatches.id, fireOccurrences.importBatchId))
      .where(and(eq(importBatches.visibility, "publico"), sql`${fireOccurrences.municipality} is not null`,
        ...(state ? [eq(fireOccurrences.state, state)] : [])))
      .orderBy(fireOccurrences.municipality).limit(1000);
    res.json(rows.map((r) => r.municipality));
  }));
}

